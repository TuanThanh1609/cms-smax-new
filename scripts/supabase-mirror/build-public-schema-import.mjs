import fs from 'node:fs';
import path from 'node:path';

const corePath = path.resolve(
  process.argv[2] || 'tmp/supabase-mirror/source-privileged/schema-core.json',
);
const accessPath = path.resolve(
  process.argv[3] || 'tmp/supabase-mirror/source-privileged/schema-access.json',
);
const outputPath = path.resolve(
  process.argv[4] || 'tmp/supabase-mirror/source-privileged/public-schema-import.sql',
);

const core = JSON.parse(fs.readFileSync(corePath, 'utf8'));
const access = JSON.parse(fs.readFileSync(accessPath, 'utf8'));

if (core.project_ref !== 'byxzjcypifhhgzyrzbfv' || access.project_ref !== 'byxzjcypifhhgzyrzbfv') {
  throw new Error('Schema export does not belong to the expected source project.');
}

const tables = core.relations.filter((relation) => relation.kind === 'r');
if (tables.length !== 9) {
  throw new Error(`Expected 9 public tables, found ${tables.length}.`);
}
if (core.views.length !== 0 || core.triggers.length !== 0) {
  throw new Error('Views or custom triggers require a manual review before rebuilding the schema.');
}

function quoteIdent(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function quoteRole(value) {
  return value.toLowerCase() === 'public' ? 'PUBLIC' : quoteIdent(value);
}

function groupBy(items, keyFn) {
  const groups = new Map();
  for (const item of items) {
    const key = keyFn(item);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(item);
  }
  return groups;
}

const lines = [
  '-- Generated from the exact source catalog export.',
  '-- Rebuilds only application objects in the public schema.',
  'begin;',
  '',
  `do $$
  declare actual text;
  begin
    select
      (select count(*) from information_schema.tables where table_schema = 'public' and table_type = 'BASE TABLE') || '|' ||
      (select count(*) from auth.users) || '|' ||
      (select count(*) from storage.objects) || '|' ||
      (select count(*) from storage.buckets where id = 'site_assets')
    into actual;
    if actual <> '9|1|299|1' then
      raise exception 'Target preflight mismatch: %, expected 9|1|299|1', actual;
    end if;
  end
  $$;`,
  '',
];

for (const table of [...tables].reverse()) {
  lines.push(`drop table if exists public.${quoteIdent(table.name)} cascade;`);
}
lines.push('');

for (const table of tables) {
  const columns = core.columns.filter((column) => column.table === table.name);
  const definitions = columns.map((column) => {
    let definition = `  ${quoteIdent(column.name)} ${column.type}`;
    if (column.collation) definition += ` collate ${quoteIdent(column.collation)}`;
    if (column.identity === 'a') definition += ' generated always as identity';
    if (column.identity === 'd') definition += ' generated by default as identity';
    if (column.generated === 's') definition += ` generated always as (${column.default}) stored`;
    else if (column.default !== null && !column.identity) definition += ` default ${column.default}`;
    if (column.not_null) definition += ' not null';
    return definition;
  });

  lines.push(`create table public.${quoteIdent(table.name)} (\n${definitions.join(',\n')}\n);`);
  lines.push(`alter table public.${quoteIdent(table.name)} owner to postgres;`);
  lines.push('');
}

for (const constraint of core.constraints) {
  lines.push(
    `alter table only public.${quoteIdent(constraint.table)} add constraint ${quoteIdent(constraint.name)} ${constraint.definition};`,
  );
}
lines.push('');

const constraintNames = new Set(core.constraints.map((constraint) => constraint.name));
for (const index of core.indexes) {
  if (!constraintNames.has(index.name)) lines.push(`${index.definition};`);
}
lines.push('');

for (const table of tables) {
  if (table.rls_enabled) lines.push(`alter table public.${quoteIdent(table.name)} enable row level security;`);
  if (table.rls_forced) lines.push(`alter table public.${quoteIdent(table.name)} force row level security;`);
}
lines.push('');

for (const fn of access.functions) {
  lines.push(fn.definition.trimEnd() + ';');
  lines.push(`alter function public.${quoteIdent(fn.name)}(${fn.identity_arguments}) owner to ${quoteIdent(fn.owner)};`);
  lines.push(`revoke all on function public.${quoteIdent(fn.name)}(${fn.identity_arguments}) from PUBLIC;`);
  lines.push('');
}

for (const policy of access.policies) {
  const roles = policy.roles.map(quoteRole).join(', ');
  let statement = `create policy ${quoteIdent(policy.name)} on public.${quoteIdent(policy.table)}`;
  statement += ` as ${policy.permissive.toLowerCase()}`;
  statement += ` for ${policy.command.toLowerCase()} to ${roles}`;
  if (policy.using) statement += ` using (${policy.using})`;
  if (policy.with_check) statement += ` with check (${policy.with_check})`;
  lines.push(statement + ';');
}
lines.push('');

lines.push('grant usage on schema public to anon, authenticated, service_role;');

const tableGrants = groupBy(
  access.table_grants.filter((grant) => grant.grantee !== 'postgres'),
  (grant) => `${grant.table_name}\u0000${grant.grantee}`,
);
for (const grants of tableGrants.values()) {
  const { table_name: tableName, grantee } = grants[0];
  const privileges = grants.map((grant) => grant.privilege_type).sort().join(', ');
  lines.push(`grant ${privileges} on table public.${quoteIdent(tableName)} to ${quoteRole(grantee)};`);
}

const sequenceGrants = groupBy(
  access.sequence_grants.filter((grant) => grant.grantee !== 'postgres'),
  (grant) => `${grant.object_name}\u0000${grant.grantee}`,
);
for (const grants of sequenceGrants.values()) {
  const { object_name: sequenceName, grantee } = grants[0];
  const privileges = grants.map((grant) => grant.privilege_type).sort().join(', ');
  lines.push(`grant ${privileges} on sequence public.${quoteIdent(sequenceName)} to ${quoteRole(grantee)};`);
}

const routineGrantees = new Map();
for (const grant of access.routine_grants) {
  if (grant.grantee === 'postgres') continue;
  if (!routineGrantees.has(grant.routine_name)) routineGrantees.set(grant.routine_name, new Set());
  routineGrantees.get(grant.routine_name).add(grant.grantee);
}
for (const fn of access.functions) {
  for (const grantee of routineGrantees.get(fn.name) || []) {
    lines.push(`grant execute on function public.${quoteIdent(fn.name)}(${fn.identity_arguments}) to ${quoteRole(grantee)};`);
  }
}

lines.push('', 'commit;', '');

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, lines.join('\n'), { encoding: 'utf8', mode: 0o600 });

console.log(JSON.stringify({
  output: outputPath,
  tables: tables.length,
  columns: core.columns.length,
  constraints: core.constraints.length,
  standaloneIndexes: core.indexes.filter((index) => !constraintNames.has(index.name)).length,
  functions: access.functions.length,
  policies: access.policies.length,
}));
